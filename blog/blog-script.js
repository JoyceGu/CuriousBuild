// Minimal JavaScript for PaperMod-style blog

document.addEventListener('DOMContentLoaded', function() {
    // Smooth scrolling for anchor links
    initSmoothScrolling();
    
    // Handle external links
    initExternalLinks();
    
    // Initialize search functionality
    initSearch();
    
    // Initialize subscription functionality
    initSubscription();
    
    // Simple fade-in animation for posts
    initPostAnimations();
});

// Smooth scrolling for anchor links
function initSmoothScrolling() {
    const links = document.querySelectorAll('a[href^="#"]');
    
    links.forEach(link => {
        link.addEventListener('click', function(e) {
            e.preventDefault();
            
            const targetId = this.getAttribute('href').substring(1);
            const targetElement = document.getElementById(targetId);
            
            if (targetElement) {
                targetElement.scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            }
        });
    });
}

// Simple fade-in animation for posts
function initPostAnimations() {
    const posts = document.querySelectorAll('.post-item');
    
    const observerOptions = {
        threshold: 0.1,
        rootMargin: '0px 0px -50px 0px'
    };
    
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.style.opacity = '1';
                entry.target.style.transform = 'translateY(0)';
            }
        });
    }, observerOptions);
    
    // Set initial styles and observe all posts
    posts.forEach((post, index) => {
        post.style.opacity = '0';
        post.style.transform = 'translateY(20px)';
        post.style.transition = `opacity 0.6s ease ${index * 0.1}s, transform 0.6s ease ${index * 0.1}s`;
        observer.observe(post);
    });
}

// Handle external links
function initExternalLinks() {
    const externalLinks = document.querySelectorAll('a[href^="http"]');
    
    externalLinks.forEach(link => {
        // Add external link indicator
        if (!link.querySelector('svg')) {
            link.setAttribute('target', '_blank');
            link.setAttribute('rel', 'noopener noreferrer');
        }
    });
}

// Simple keyboard navigation
document.addEventListener('keydown', function(e) {
    // Press 'h' to go home
    if (e.key === 'h' && !e.ctrlKey && !e.metaKey && !e.altKey) {
        const activeElement = document.activeElement;
        if (activeElement.tagName !== 'INPUT' && activeElement.tagName !== 'TEXTAREA') {
            window.location.href = '/';
        }
    }
});

// Add minimal loading animation
window.addEventListener('load', function() {
    document.body.style.opacity = '1';
});

// Set initial opacity to 0 for loading animation
document.body.style.opacity = '0';
document.body.style.transition = 'opacity 0.3s ease';

// Search functionality
function initSearch() {
    console.log('initSearch called');
    const searchInput = document.getElementById('searchInput');
    const searchBtn = document.getElementById('searchBtn');
    const searchResults = document.getElementById('searchResults');
    
    console.log('Search elements:', { searchInput, searchBtn, searchResults });
    
    if (!searchInput || !searchBtn || !searchResults) {
        console.error('Search elements not found!');
        return;
    }
    
    console.log('Search functionality initialized successfully');
    
    // Article data for search, generated by build.py
    let articles = [];
    fetch('posts.json')
        .then(response => response.ok ? response.json() : [])
        .then(data => { articles = data; })
        .catch(error => console.error('Could not load search index:', error));

    const t = (key) => (window.I18n ? window.I18n.t(key) : key);

    let searchTimeout;
    
    // Search function
    function performSearch(query) {
        console.log('Performing search for:', query);
        if (!query.trim()) {
            hideSearchResults();
            return;
        }
        
        const uiLang = window.I18n ? window.I18n.lang : 'en';
        const results = articles.filter(article => {
            // Same rule as the post list: skip the other-language copy of a translated post
            if (article.has_translation && article.lang !== uiLang) return false;
            const searchText = [article.title, article.summary, (article.tags || []).join(' '), article.content]
                .join(' ')
                .toLowerCase();
            return searchText.includes(query.toLowerCase());
        });
        
        console.log('Search results:', results);
        displaySearchResults(results, query);
    }
    
    // Display search results
    function displaySearchResults(results, query) {
        if (results.length === 0) {
            searchResults.innerHTML = `<div class="search-no-results">${t('blog.noResults')}</div>`;
        } else {
            const resultsHTML = results.map(article => {
                const highlightedTitle = highlightText(article.title, query);
                const highlightedSummary = highlightText(article.summary, query);
                const date = window.I18n ? window.I18n.formatDate(article.date) : article.date;
                
                return `
                    <div class="search-result-item" onclick="window.location.href='${article.url}'">
                        <div class="search-result-title">${highlightedTitle}</div>
                        <div class="search-result-summary">${highlightedSummary}</div>
                        <div class="search-result-meta">${date}</div>
                    </div>
                `;
            }).join('');
            
            searchResults.innerHTML = resultsHTML;
        }
        
        searchResults.style.display = 'block';
    }
    
    // Hide search results
    function hideSearchResults() {
        searchResults.style.display = 'none';
    }
    
    // Highlight search terms
    function highlightText(text, query) {
        if (!query.trim()) return text;
        
        const regex = new RegExp(`(${escapeRegExp(query)})`, 'gi');
        return text.replace(regex, '<span class="search-highlight">$1</span>');
    }
    
    // Escape special regex characters
    function escapeRegExp(string) {
        return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }
    
    // Event listeners
    searchInput.addEventListener('input', function() {
        console.log('Search input changed:', this.value);
        clearTimeout(searchTimeout);
        searchTimeout = setTimeout(() => {
            performSearch(this.value);
        }, 300);
    });
    
    searchBtn.addEventListener('click', function() {
        console.log('Search button clicked');
        performSearch(searchInput.value);
    });
    
    searchInput.addEventListener('keydown', function(e) {
        if (e.key === 'Enter') {
            e.preventDefault();
            performSearch(this.value);
        }
        if (e.key === 'Escape') {
            hideSearchResults();
            this.blur();
        }
    });
    
    // Hide search results when clicking outside
    document.addEventListener('click', function(e) {
        if (!e.target.closest('.search-container')) {
            hideSearchResults();
        }
    });
}

// Subscription functionality: the form posts to Buttondown (see subscribe-config.js),
// which stores subscribers and sends them a confirmation email
function initSubscription() {
    const t = (key) => (window.I18n ? window.I18n.t(key) : key);
    const subscribeBtn = document.getElementById('subscribeBtn');
    const modal = document.getElementById('subscriptionModal');
    const closeBtn = document.getElementById('closeModal');
    const subscriptionForm = document.getElementById('subscriptionForm');
    const emailInput = document.getElementById('emailInput');
    const formMessage = document.getElementById('formMessage');

    initRssLinks();

    if (!subscribeBtn || !modal || !subscriptionForm) {
        return;
    }

    const config = window.BLOG_SUBSCRIBE || {};
    const username = (config.buttondownUsername || '').trim();
    if (!username) {
        // Not set up yet: don't show a form that goes nowhere
        subscribeBtn.style.display = 'none';
        document.querySelectorAll('.or-text').forEach(el => { el.style.display = 'none'; });
        return;
    }

    subscriptionForm.action = `https://buttondown.com/api/emails/embed-subscribe/${encodeURIComponent(username)}`;
    subscriptionForm.method = 'post';
    subscriptionForm.target = '_blank';

    subscribeBtn.addEventListener('click', function() {
        modal.classList.add('show');
        emailInput.focus();
        hideMessage();
    });

    closeBtn.addEventListener('click', closeModal);

    modal.addEventListener('click', function(e) {
        if (e.target === modal) {
            closeModal();
        }
    });

    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape' && modal.classList.contains('show')) {
            closeModal();
        }
    });

    function closeModal() {
        modal.classList.remove('show');
        subscriptionForm.reset();
        hideMessage();
    }

    // Let the browser submit the form to Buttondown (opens its confirmation page
    // in a new tab); only block it when the address is obviously invalid
    subscriptionForm.addEventListener('submit', function(e) {
        const email = emailInput.value.trim();
        if (!isValidEmail(email)) {
            e.preventDefault();
            showMessage(t('msg.invalidEmail'), 'error');
            return;
        }
        showMessage(t('msg.checkInbox'), 'success');
        setTimeout(closeModal, 4000);
    });

    function isValidEmail(email) {
        const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        return emailRegex.test(email);
    }

    function showMessage(text, type) {
        formMessage.textContent = text;
        formMessage.className = `form-message ${type}`;
    }

    function hideMessage() {
        formMessage.className = 'form-message';
        formMessage.textContent = '';
    }
}

// RSS links point at the feed for the current language
function initRssLinks() {
    const update = () => {
        const lang = window.I18n ? window.I18n.lang : 'en';
        document.querySelectorAll('a[href$="feed.xml"], a[data-feed-link]').forEach(link => {
            link.dataset.feedLink = 'true';
            link.setAttribute('href', `feed-${lang}.xml`);
        });
    };
    update();
    document.addEventListener('langchange', update);
}
